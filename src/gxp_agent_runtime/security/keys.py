"""Ed25519 signing keys for electronic-signature manifests, execution records and audit.

Private keys are mounted from the cloud secret manager; they are never
generated by infrastructure code. Public keys are published at
``/.well-known/jwks.json`` so auditors can verify records offline.
"""

from __future__ import annotations

import base64
from pathlib import Path
from typing import Any

import jwt
from agentic_core.domain.provenance import canonical_json
from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey


class RecordSigner:
    def __init__(self, key: Ed25519PrivateKey, key_id: str) -> None:
        self._key = key
        self.key_id = key_id

    @classmethod
    def ephemeral(cls, key_id: str) -> RecordSigner:
        return cls(Ed25519PrivateKey.generate(), key_id)

    @classmethod
    def from_file(cls, path: Path) -> RecordSigner:
        key = serialization.load_pem_private_key(path.read_bytes(), password=None)
        if not isinstance(key, Ed25519PrivateKey):
            raise ValueError(f"{path.name} must hold an Ed25519 private key")
        return cls(key, path.stem)

    @property
    def public_key(self) -> Ed25519PublicKey:
        return self._key.public_key()

    def sign(self, data: bytes) -> bytes:
        return self._key.sign(data)

    def sign_document(self, document: dict[str, Any]) -> str:
        return base64.b64encode(self._key.sign(canonical_json(document))).decode()

    def jwk(self, use: str) -> dict[str, Any]:
        jwk: dict[str, Any] = jwt.algorithms.OKPAlgorithm.to_jwk(self.public_key, as_dict=True)
        jwk.update({"kid": self.key_id, "alg": "EdDSA", "use": use})
        return jwk


class SignatureVerifier:
    """Public keys by key id: the active signers plus retired keys kept for verification."""

    def __init__(self, keys: dict[str, Ed25519PublicKey]) -> None:
        self._keys = dict(keys)

    @classmethod
    def from_directory(cls, directory: Path) -> dict[str, Ed25519PublicKey]:
        found: dict[str, Ed25519PublicKey] = {}
        for path in sorted(directory.glob("*.pem")):
            key = serialization.load_pem_public_key(path.read_bytes())
            if not isinstance(key, Ed25519PublicKey):
                raise ValueError(f"{path.name} must hold an Ed25519 public key")
            found[path.stem] = key
        return found

    @property
    def keys(self) -> dict[str, Ed25519PublicKey]:
        return dict(self._keys)

    def verify_document(self, key_id: str, document: dict[str, Any], signature: str) -> bool:
        key = self._keys.get(key_id)
        if key is None:
            return False
        try:
            key.verify(base64.b64decode(signature), canonical_json(document))
        except (InvalidSignature, ValueError):
            return False
        return True
